/* ====================================================================
   Per-project gallery generator — deterministic, 6-14 photos, sectioned
   When real photos arrive, swap `swatch` for an `img` field, layout stays.
   ==================================================================== */
window.RA_PROJECT_GALLERY = (project) => {
  const swatches = ["basalt","teak","stone","concrete","clay","lime","ivory","slate","marsh","terrazzo"];
  // deterministic from slug
  let seed = 0; for (const c of project.slug) seed = (seed * 31 + c.charCodeAt(0)) % 9973;
  const rng = () => { seed = (seed * 9301 + 49297) % 233280; return seed / 233280; };

  const sections = [
    { name: "Exterior",  variants: [project.swatch, project.swatch, "stone"],          ratios: ["16/9", "4/5", "3/4"] },
    { name: "Approach",  variants: [project.swatch, "stone", project.swatch+" plan"],  ratios: ["3/2", "4/3"] },
    { name: "Interior",  variants: [project.swatch+" interior", project.swatch+" interior", "teak interior"], ratios: ["4/5", "3/4", "1/1", "16/9"] },
    { name: "Detail",    variants: ["concrete","stone","slate","teak"],                ratios: ["1/1", "4/5", "3/4"] },
    { name: "Plan",      variants: [project.swatch+" plan", "ivory plan"],              ratios: ["4/3", "3/2"] },
  ];

  // pick 3-5 sections deterministically
  const sectionCount = 3 + Math.floor(rng() * 3); // 3..5
  const chosen = sections.slice(0, sectionCount);

  const photos = [];
  chosen.forEach((sec) => {
    const count = 2 + Math.floor(rng() * 3); // 2..4 photos per section
    for (let i = 0; i < count; i++) {
      photos.push({
        section: i === 0 ? sec.name : null,
        swatch:  sec.variants[Math.floor(rng() * sec.variants.length)],
        ratio:   sec.ratios[Math.floor(rng() * sec.ratios.length)],
        caption: i === 0 ? `${sec.name.toLowerCase()} · ${project.location.split(",")[0]}` : null,
      });
    }
  });
  return photos;
};

